#!/usr/bin/env python3
"""Cuts public/images/12toons-logo.png into separate layers (digits, swoosh, pencil, wordmark letters, play button, underline) for the loading animation.
Every non-white pixel goes to exactly one layer and is copied unchanged, so the layers stacked together are the original logo.
Usage: python3 scripts/make_logo_layers.py   (writes public/images/logo-anim/*.webp)"""
import sys, json
from pathlib import Path
import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'public/images/12toons-logo.png'
OUT = ROOT / 'public/images/logo-anim'
SIZE = 384

im = Image.open(SRC).convert('RGBA')
a = np.array(im).astype(int)
r, g, b, al = a[..., 0], a[..., 1], a[..., 2], a[..., 3]
H, W = r.shape
yy, xx = np.mgrid[0:H, 0:W]
ink = (np.minimum(np.minimum(r, g), b) < 244) & (al > 200)
orange = ink & (r > b + 55) & (r > 150)
blue = ink & (b > r + 50) & ~orange

def runs(mask_cols):
    out, start = [], None
    for i, v in enumerate(mask_cols):
        if v and start is None: start = i
        if not v and start is not None: out.append((start, i - 1)); start = None
    if start is not None: out.append((start, len(mask_cols) - 1))
    return out

word = (yy >= 555) & (yy <= 700)
cols_ink = (ink & word & (yy < 690)).any(axis=0)
glyph_runs = [rg for rg in runs(cols_ink) if rg[1] - rg[0] > 6]
print('wordmark glyph column runs:', glyph_runs, file=sys.stderr)

layers = {}
pencil = ink & (xx >= 70) & (xx <= 205) & (yy >= 370) & (yy <= 535)
layers['pencil'] = pencil
rest = ink & ~pencil
top = rest & (yy < 540)
layers['one'] = top & blue & (xx < 310)
layers['two'] = top & blue & (xx >= 310)
layers['swoosh'] = rest & orange & (yy < 555)
low = rest & (yy >= 555)
layers['under'] = low & orange & (yy >= 690)
# the play triangle sits inside the "o"; the letters are cut at the gaps between the glyph columns
# "12Toons": the T's bar overhangs the first "o", so the T is cut by region; the other letters are cut at the gaps between them (measured on the picture)
navy = low & ~orange & ~blue & (yy < 700)
layers['w12'] = navy & (xx < 252)
letters = low & blue & (yy < 700)
t_part = letters & ((xx < 327) | ((xx < 352) & (yy < 590)))
layers['w_t'] = t_part
rest_letters = letters & ~t_part
layers['w_o1'] = rest_letters & (xx < 415)
layers['w_o2'] = rest_letters & (xx >= 415) & (xx < 506)
layers['w_n'] = rest_letters & (xx >= 506) & (xx < 585)
layers['w_s'] = rest_letters & (xx >= 585)
play = low & orange & (yy < 690)
layers['play'] = play
# ink pixels of the wordmark row that no rule claimed (e.g. dark navy letters right of the "12") stay on the plate

taken = np.zeros_like(ink)
for k, m in layers.items():
    assert not (taken & m).any(), k
    taken |= m

# the plate: the original, with the moving layers painted out by the surrounding paper colour
src_rgb = im.convert('RGB')
paper = src_rgb.filter(ImageFilter.MaxFilter(31)).filter(ImageFilter.MaxFilter(31))
plate = np.array(im).copy()
pap = np.array(paper)
plate[taken, :3] = pap[taken]

OUT.mkdir(parents=True, exist_ok=True)
def save(arr, name):
    img = Image.fromarray(arr.astype('uint8'), 'RGBA').convert('RGBa').resize((SIZE, SIZE), Image.LANCZOS).convert('RGBA')
    img.save(OUT / (name + '.webp'), 'WEBP', lossless=True, quality=100, method=6)
    return img
resized = {}
PLATE = (251, 251, 253)
# the picture's rounded-square outline (a squircle, not a plain circular corner): measured per row from the alpha channel, then mirrored to the other corners
alpha = np.array(im)[..., 3].astype(float) / 255
TL = [(round(384 - alpha[y, :384].sum(), 1), y) for y in range(0, 170, 3)] + [(0.0, 170)]
BL = [(x, 768 - y) for x, y in reversed(TL)]
BR = [(768 - x, 768 - y) for x, y in TL]
TR = [(768 - x, y) for x, y in reversed(TL)]
OUTLINE = TL + BL + BR + TR
PLATE_PATH = 'M' + ' L'.join('%g %g' % p for p in OUTLINE) + 'Z'
from PIL import ImageDraw
flat = Image.new('RGBA', (768, 768), (0, 0, 0, 0))
ImageDraw.Draw(flat).polygon(OUTLINE, fill=PLATE + (255,))
resized['plate'] = flat.convert('RGBa').resize((SIZE, SIZE), Image.LANCZOS).convert('RGBA')   # only for the check below, not saved
base = np.array(im)
for k, m in layers.items():
    arr = np.zeros_like(base); arr[m] = base[m]
    resized[k] = save(arr, k)

# check: stack everything back together and compare with the original at the same size
ref = im.convert('RGBa').resize((SIZE, SIZE), Image.LANCZOS).convert('RGBA')
comp = resized['plate'].copy()
for k in layers: comp = Image.alpha_composite(comp, resized[k])
diff = np.abs(np.array(comp).astype(int) - np.array(ref).astype(int))
print('layers:', {k: int(m.sum()) for k, m in layers.items()}, file=sys.stderr)
print('max diff', int(diff.max()), 'mean diff', round(float(diff.mean()), 3), file=sys.stderr)
(ROOT / 'src/logo-anim-data.js').write_text("// Generated by scripts/make_logo_layers.py. The 12toons logo, cut into layers (public/images/logo-anim/*.webp) and its rounded-square outline.\n"
    "export const LOGO_VIEW = 768;\nexport const LOGO_PLATE = { fill: '%s', path: '%s' };\nexport const LOGO_LAYERS = %s;\n" % ('#%02x%02x%02x' % PLATE, PLATE_PATH, json.dumps(list(layers.keys()))))
